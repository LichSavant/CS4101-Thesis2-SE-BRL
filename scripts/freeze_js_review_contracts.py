"""Generate static compatibility metadata, never observations or model output."""
from dataclasses import asdict
import hashlib
from html.entities import html5
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ml.se_brl.rules import RULES, RULESET_VERSION
from ml.se_brl import context, detectors
from ml.se_brl.semantic_review import preprocessing_contract

OUT = ROOT / "tools/verification/js-review/contracts.mjs"


def generate():
    paths = ["ml/preprocessing.py", "ml/datasets.py", "ml/metadata.py", "ml/research_policy.py",
             "ml/annotation_validation.py", "ml/se_brl/context.py", "ml/se_brl/detectors.py",
             "ml/se_brl/extraction.py", "ml/se_brl/rules.py", "ml/se_brl/assessment.py",
             "ml/se_brl/semantic_review.py", "ml/se_brl/semantic_candidates.py", "ml/se_brl/review_adapter.py",
             "ml/se_brl/codebook.v0.1.0.json", "ml/se_brl/semantic-model.v1.json",
             "experiments/vera_validation/V13_nli_hypotheses_v0.1.0.json"]
    data = dict(rules=[asdict(r) for r in RULES], ruleset=RULESET_VERSION,
                codebook=json.loads((ROOT / paths[-3]).read_text()),
                model=json.loads((ROOT / paths[-2]).read_text()),
                hypotheses=json.loads((ROOT / paths[-1]).read_text()),
                preprocessing=preprocessing_contract(),
                patterns={name: getattr(module, name).pattern for module, names in (
                    (context, ("NEGATION", "EDUCATIONAL", "REPORTED", "COUNTEREXAMPLE", "QUOTATION")),
                    (detectors, ("ROLE", "DIRECTIVE", "DOMAIN"))) for name in names},
                entities=html5,
                casefold={chr(n): chr(n).casefold() for n in range(sys.maxunicode + 1)
                          if chr(n).casefold() != chr(n).lower()},
                excluded_hashes=json.loads((ROOT / "ml/research-inputs.v1.json").read_text())["excluded_file_sha256"],
                source_sha256={p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in paths})
    return "// Generated by scripts/freeze_js_review_contracts.py; no inferred labels.\nexport default " + json.dumps(data, ensure_ascii=True, separators=(",", ":")) + ";\n"


if __name__ == "__main__":
    value = generate()
    if "--check" in sys.argv:
        assert OUT.read_text(encoding="utf-8") == value, "Static contract/source drift"
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(value, encoding="utf-8", newline="\n")
    print("JS_CONTRACTS_VERIFIED")
